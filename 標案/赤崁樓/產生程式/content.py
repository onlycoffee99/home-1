# ---------------- 財務試算 ----------------
DAYS_M = 26                      # 每月營業日(每週營業 6 日)
CUST = 120                       # 平均每日來客數
TICKET = 230                     # 平均客單價
FB_M = DAYS_M * CUST * TICKET    # 餐飲月營收
RET_M = 60000                    # 文創/伴手禮月營收
EVT_M = 30000                    # 沙龍、包場及活動月收入
RAMP = [0.8, 1.0, 1.05]
FIX_ROY_M = 40000                # 固定權利金(月)
VAR_ROY = 0.01                   # 變動權利金(年營業額 1%)
CAPEX = 1700000                  # 開辦投入
DEP_Y = 3

def year(i):
    r = RAMP[i]
    fb, ret, evt = FB_M*12*r, RET_M*12*r, EVT_M*12*r
    rev = fb+ret+evt
    c = {
        '餐飲原物料成本(餐飲營收32%)': fb*0.32,
        '商品進貨成本(商品營收55%)': ret*0.55,
        '人事費用(含勞健保、退休金)': 2520000*(1 if i < 2 else 1.03),
        '固定權利金': FIX_ROY_M*12,
        '變動權利金(營業額1%)': rev*VAR_ROY,
        '水電瓦斯及通訊費': 420000,
        '行銷推廣費(營業額3%)': rev*0.03,
        '保險、清潔、消防及設備維護': 180000,
        '耗材及雜支(營業額2%)': rev*0.02,
        '開辦裝修及設備攤提(3年)': CAPEX/DEP_Y,
    }
    return fb, ret, evt, rev, c

Y = [year(i) for i in range(3)]
def n(x): return f'{round(x):,}'

# 損益兩平
fixed = 2520000 + FIX_ROY_M*12 + 420000 + 180000 + CAPEX/DEP_Y
# 變動成本率:以第二年營收結構計
fb, ret, evt, rev, c = Y[1]
var_rate = (fb*0.32 + ret*0.55)/rev + VAR_ROY + 0.03 + 0.02
BEP = fixed/(1-var_rate)
BEP_M = BEP/12
BEP_CUST = (BEP_M - (RET_M+EVT_M)) / DAYS_M / TICKET

