    rows.append(['　餐飲收入(茶飲、咖啡、輕食)'] + [n(y[0]) for y in Y])
    rows.append(['　文創商品及伴手禮收入'] + [n(y[1]) for y in Y])
    rows.append(['　文化沙龍、包場及活動收入'] + [n(y[2]) for y in Y])
    rows.append(['營業收入合計'] + [n(y[3]) for y in Y])
    rows.append(['營業成本及費用', '', '', ''])
    for k in Y[0][4]:
        rows.append(['　'+k] + [n(y[4][k]) for y in Y])
    rows.append(['成本及費用合計'] + [n(sum(y[4].values())) for y in Y])
